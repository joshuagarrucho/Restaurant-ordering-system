create or replace function public.esmiringkape_calculate_order_totals(p_order_id bigint)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_subtotal numeric(12,2);
  v_discount_rate numeric(7,4);
  v_tax_rate numeric(7,4);
  v_discount numeric(12,2);
  v_tax numeric(12,2);
begin
  select coalesce(sum(oi."LineTotal"), 0)::numeric(12,2)
    into v_subtotal
  from public."OrderItem" oi where oi."OrderID" = p_order_id;

  select least(100, coalesce(sum("RatePercent"), 0)) into v_discount_rate
  from public."DiscountRule" where "IsActive";
  select coalesce(sum("RatePercent"), 0) into v_tax_rate
  from public."TaxRule" where "IsActive";

  v_discount := round(v_subtotal * v_discount_rate / 100, 2);
  v_tax := round((v_subtotal - v_discount) * v_tax_rate / 100, 2);
  update public."Order"
    set "Subtotal" = v_subtotal,
        "DiscountAmount" = v_discount,
        "TaxAmount" = v_tax,
        "TotalAmount" = v_subtotal - v_discount + v_tax
  where "OrderID" = p_order_id;
end;
$$;

create or replace function public.esmiringkape_snapshot_order_item()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_name text;
  v_price numeric(12,2);
  v_available boolean;
begin
  select mi."ItemName", mi."Price"::numeric(12,2), mi."Available"
    into v_name, v_price, v_available
  from public."MenuItems" mi where mi."ItemID" = new."ItemID";
  if v_price is null then raise exception 'Menu item is unavailable or missing'; end if;
  if tg_op = 'INSERT' and v_available is distinct from true then
    raise exception 'Menu item is unavailable or missing';
  end if;
  if tg_op = 'INSERT' then
    new."ItemNameSnapshot" := v_name;
    new."UnitPrice" := v_price;
  else
    new."ItemNameSnapshot" := coalesce(new."ItemNameSnapshot", v_name);
    new."UnitPrice" := coalesce(new."UnitPrice", v_price);
  end if;
  if new."Quantity" <= 0 then raise exception 'Quantity must be positive'; end if;
  new."LineTotal" := round(new."UnitPrice" * new."Quantity", 2);
  return new;
end;
$$;

drop trigger if exists order_item_price_snapshot on public."OrderItem";
create trigger order_item_price_snapshot
before insert or update of "ItemID", "Quantity", "UnitPrice"
on public."OrderItem"
for each row execute function public.esmiringkape_snapshot_order_item();

create or replace function public.esmiringkape_refresh_order_totals_trigger()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  perform public.esmiringkape_calculate_order_totals(coalesce(new."OrderID", old."OrderID"));
  return null;
end;
$$;

drop trigger if exists order_item_totals_recalc on public."OrderItem";
create trigger order_item_totals_recalc
after insert or update or delete on public."OrderItem"
for each row execute function public.esmiringkape_refresh_order_totals_trigger();

-- Existing items are kept. This one-time backfill records a price snapshot from current menu data
-- only where a historical snapshot was never stored.
update public."OrderItem" oi
set "ItemNameSnapshot" = coalesce(oi."ItemNameSnapshot", mi."ItemName"),
    "UnitPrice" = coalesce(oi."UnitPrice", mi."Price"),
    "LineTotal" = coalesce(oi."LineTotal", mi."Price" * oi."Quantity")
from public."MenuItems" mi
where mi."ItemID" = oi."ItemID"
  and (oi."UnitPrice" is null or oi."LineTotal" is null or oi."ItemNameSnapshot" is null);

update public."Payment"
set "AmountApplied" = coalesce("AmountApplied", case when lower(coalesce("PaymentStatus", '')) in ('paid', 'partially refunded', 'refunded') then "AmountPaid" end),
    "CashTendered" = coalesce("CashTendered", case when lower(coalesce("PaymentStatus", '')) in ('paid', 'partially refunded', 'refunded') then "AmountPaid" end),
    "ChangeGiven" = coalesce("ChangeGiven", 0)
where "AmountApplied" is null or "CashTendered" is null or "ChangeGiven" is null;

-- Existing OrderID is the persistent database-generated ticket identifier and remains the source
-- of truth. It is never derived from visible orders or a browser counter.
update public."Order" o
set "TotalAmount" = coalesce(o."TotalAmount", (
      select sum(oi."LineTotal") from public."OrderItem" oi where oi."OrderID" = o."OrderID"
    )),
    "Subtotal" = coalesce(o."Subtotal", (
      select sum(oi."LineTotal") from public."OrderItem" oi where oi."OrderID" = o."OrderID"
    ));

alter table public."TaxRule" enable row level security;
alter table public."DiscountRule" enable row level security;
alter table public."ShopSetting" enable row level security;
alter table public."SaleIdempotency" enable row level security;
revoke all on public."TaxRule", public."DiscountRule", public."ShopSetting", public."SaleIdempotency" from anon, authenticated;

-- Totals are recalculated only by trusted transaction functions and triggers.
revoke all on function public.esmiringkape_calculate_order_totals(bigint) from public, anon, authenticated;
revoke all on function public.esmiringkape_snapshot_order_item() from public, anon, authenticated;
revoke all on function public.esmiringkape_refresh_order_totals_trigger() from public, anon, authenticated;

commit;

